#!/usr/bin/env bash
# Writes /etc/homelab/firewall.conf (once), the nftables rules generated from
# it, and the unit that loads them. Nothing is applied here: start does that.
set -euo pipefail
# shellcheck disable=SC1091
. "$HOMELAB_ROOT/lib/contract.sh"

CONF="$HOMELAB_ETC/firewall.conf"
NFT_FILE="$HOMELAB_ETC/firewall.nft"
NFT="$(command -v nft || echo /usr/sbin/nft)"

if ! [ -x "$NFT" ]; then
    log "installing nftables"
    run $SUDO env DEBIAN_FRONTEND=noninteractive apt-get install -y -qq nftables
    NFT=/usr/sbin/nft
fi

# --- settings: detected once, then yours to edit -----------------------------
if ! $SUDO test -f "$CONF"; then
    iface="$(ip route 2>/dev/null | awk '/^default/{print $5; exit}')"
    lan="$(ip -4 route show dev "${iface:-none}" proto kernel scope link 2>/dev/null | awk '{print $1; exit}')"
    [ -n "$lan" ] || die "could not find this machine's LAN subnet; write $CONF by hand (see apps/firewall/download.sh)"
    ok "detected LAN $lan on $iface"
    run_write "$CONF" 0644 <<CONFIG
# homelab firewall settings. After editing: homelab update firewall --apply
# (then check you can still get in, and: homelab confirm firewall --apply)

# Networks that may reach everything (space-separated, IPv4 CIDR).
LAN_NETS="$lan"
# Interfaces that may reach everything. Never remove tailscale0 while you
# manage this box over Tailscale.
TRUSTED_IFACES="tailscale0"
# Interfaces of friends' networks (Hamachi) and the ports they may reach.
FRIEND_IFACES="ham0"
FRIEND_TCP=""
FRIEND_UDP=""
# Ports open to the whole internet. Behind CGNAT this matters for IPv6 only.
PUBLIC_TCP=""
PUBLIC_UDP=""
CONFIG
fi

# --- rules ---------------------------------------------------------------------
if is_apply; then
    # shellcheck disable=SC1090
    . "$CONF"
else
    LAN_NETS="10.0.0.0/24"; TRUSTED_IFACES="tailscale0"; FRIEND_IFACES="ham0"
    FRIEND_TCP=""; FRIEND_UDP=""; PUBLIC_TCP=""; PUBLIC_UDP=""
fi
# Every value goes into the ruleset, so accept only what its type allows.
for v in $LAN_NETS; do [[ "$v" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}/[0-9]{1,2}$ ]] || die "LAN_NETS: not an IPv4 CIDR: $v"; done
for v in $TRUSTED_IFACES $FRIEND_IFACES; do [[ "$v" =~ ^[A-Za-z0-9_.*-]{1,15}$ ]] || die "not an interface name: $v"; done
for v in $FRIEND_TCP $FRIEND_UDP $PUBLIC_TCP $PUBLIC_UDP; do [[ "$v" =~ ^[0-9]{1,5}(-[0-9]{1,5})?$ ]] || die "not a port or port range: $v"; done

set_of() {  # set_of quote? words... -> { a, b } ; empty -> nothing
    local q="$1"; shift
    local out="" w
    for w in "$@"; do
        if [ "$q" = 1 ]; then out="$out\"$w\", "; else out="$out$w, "; fi
    done
    printf '{ %s }' "${out%, }"
}
lines=""
add() { lines="$lines    $*"$'\n'; }
# shellcheck disable=SC2086
{
    [ -z "$TRUSTED_IFACES" ] || add "iifname $(set_of 1 $TRUSTED_IFACES) accept"
    [ -z "$LAN_NETS" ]       || add "ip saddr $(set_of 0 $LAN_NETS) accept"
    if [ -n "$FRIEND_IFACES" ]; then
        [ -z "$FRIEND_TCP" ] || add "iifname $(set_of 1 $FRIEND_IFACES) tcp dport $(set_of 0 $FRIEND_TCP) accept"
        [ -z "$FRIEND_UDP" ] || add "iifname $(set_of 1 $FRIEND_IFACES) udp dport $(set_of 0 $FRIEND_UDP) accept"
    fi
    [ -z "$PUBLIC_TCP" ] || add "tcp dport $(set_of 0 $PUBLIC_TCP) accept"
    [ -z "$PUBLIC_UDP" ] || add "udp dport $(set_of 0 $PUBLIC_UDP) accept"
}
fwd=""
# shellcheck disable=SC2086
{
    [ -z "$TRUSTED_IFACES" ] || fwd="$fwd    iifname $(set_of 1 $TRUSTED_IFACES) accept"$'\n'
    [ -z "$LAN_NETS" ]       || fwd="$fwd    ip saddr $(set_of 0 $LAN_NETS) accept"$'\n'
}

tmp="$(mktemp)"
cat > "$tmp" <<RULES
# Generated by homelab from $CONF -- edit that file, not this one.
table inet homelab
delete table inet homelab
table inet homelab {
  chain input {
    type filter hook input priority filter; policy accept;
    iif "lo" accept
    ct state established,related accept
    ct state invalid drop
    meta l4proto { icmp, ipv6-icmp } accept
    ip6 saddr fe80::/10 accept
    iifname { "docker0", "br-*" } accept
    udp dport 41641 accept
$lines    counter drop
  }
  chain forward {
    type filter hook forward priority filter; policy accept;
    ct state established,related accept
    iifname { "docker0", "br-*" } accept
$fwd    oifname { "docker0", "br-*" } counter drop
  }
}
RULES

if is_apply; then
    # A ruleset that does not parse is never installed.
    $SUDO "$NFT" -c -f "$tmp" || { rm -f "$tmp"; die "the generated rules do not parse; nothing changed"; }
fi
run_write "$NFT_FILE" 0644 < "$tmp"
rm -f "$tmp"

run_write /etc/systemd/system/homelab-firewall.service 0644 <<UNIT
[Unit]
Description=homelab firewall (nftables table inet homelab)
Wants=network-pre.target
Before=network-pre.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$NFT -f $NFT_FILE
ExecReload=$NFT -f $NFT_FILE
ExecStop=-$NFT delete table inet homelab

[Install]
WantedBy=multi-user.target
UNIT
run $SUDO systemctl daemon-reload
ok "firewall rules written to $NFT_FILE (start applies them)"
